/**
 * Generates one Vue icon component per SVG in `src/svg/`, plus the `src/index.ts` barrel.
 *
 * Each SVG is optimized with SVGO, its placeholder colors are swapped for `currentColor`, and the
 * markup becomes a static render function (`h()` calls). No `innerHTML` is used at runtime.
 *
 * Usage: node scripts/generate.mjs
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { optimize } from 'svgo'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const SVG_DIR = path.join(root, 'src', 'svg')
const OUT_DIR = path.join(root, 'src', 'icons')
const HEADER = '/* Generated by scripts/generate.mjs. Do not edit by hand. */'

/** Colors used by the design source files that should follow the surrounding text color. */
const CURRENT_COLOR_VALUES = new Set(['#898989', '#fff', '#ffffff', 'white'])

/** @param {string} name kebab-case file name */
export function toComponentName(name) {
  const pascal = name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
  return `${/^\d/.test(pascal) ? 'Icon' : ''}${pascal}Icon`
}

/**
 * @typedef {{ tag: string, attrs: Record<string, string>, children: SvgNode[] }} SvgNode
 */

const TAG_RE = /<(\/?)([a-zA-Z][\w:-]*)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g
const ATTR_RE = /([\w:-]+)="([^"]*)"/g

/**
 * Parses SVGO output into a node tree. SVGO emits normalized XML (double-quoted attributes, no
 * comments or text content in these icons), which is all this parser supports.
 * @param {string} markup
 * @returns {SvgNode}
 */
export function parseSvg(markup) {
  /** @type {SvgNode[]} */
  const stack = []
  /** @type {SvgNode | undefined} */
  let rootNode

  for (const [, closing, tag, rawAttrs, selfClosing] of markup.matchAll(TAG_RE)) {
    if (closing) {
      const node = stack.pop()
      if (node?.tag !== tag) throw new Error(`Mismatched </${tag}>`)
      continue
    }

    /** @type {SvgNode} */
    const node = {
      tag,
      attrs: Object.fromEntries([...rawAttrs.matchAll(ATTR_RE)].map(([, k, v]) => [k, v])),
      children: [],
    }
    const parent = stack.at(-1)
    if (parent) parent.children.push(node)
    else rootNode = node
    if (!selfClosing) stack.push(node)
  }

  if (!rootNode || rootNode.tag !== 'svg') throw new Error('Expected an <svg> root element')
  return rootNode
}

/** @param {Record<string, string>} attrs */
function normalizeColors(attrs) {
  for (const key of ['fill', 'stroke']) {
    const value = attrs[key]?.toLowerCase()
    if (value && CURRENT_COLOR_VALUES.has(value)) attrs[key] = 'currentColor'
  }
  return attrs
}

/**
 * @param {SvgNode} node
 * @param {string} indent
 * @returns {string}
 */
function renderNode(node, indent) {
  const attrs = JSON.stringify(normalizeColors({ ...node.attrs }))
  if (!node.children.length) return `${indent}h('${node.tag}', ${attrs})`
  const children = node.children.map((child) => renderNode(child, `${indent}  `)).join(',\n')
  return `${indent}h('${node.tag}', ${attrs}, [\n${children},\n${indent}])`
}

/**
 * @param {string} fileName kebab-case name without extension
 * @param {string} svg raw SVG source
 */
export function generateIcon(fileName, svg) {
  const { data } = optimize(svg, {
    multipass: true,
    plugins: [
      'preset-default',
      'removeDimensions',
      { name: 'prefixIds', params: { prefix: `gs-${fileName}` } },
    ],
  })

  const svgNode = parseSvg(data)
  const viewBox = svgNode.attrs.viewBox ?? '0 0 24 24'
  const name = toComponentName(fileName)
  const children = svgNode.children.map((child) => renderNode(child, '  ')).join(',\n')

  return `${HEADER}

import { h } from 'vue'
import { createIcon } from '../create-icon.js'

/** \`${fileName}\` icon */
const ${name} = createIcon('${name}', '${viewBox}', () => [
${children},
])

export default ${name}
`
}

export function main() {
  const files = readdirSync(SVG_DIR)
    .filter((file) => file.endsWith('.svg'))
    .sort()

  rmSync(OUT_DIR, { recursive: true, force: true })
  mkdirSync(OUT_DIR, { recursive: true })

  const exports = []
  for (const file of files) {
    const fileName = file.replace(/\.svg$/, '')
    writeFileSync(
      path.join(OUT_DIR, `${fileName}.ts`),
      generateIcon(fileName, readFileSync(path.join(SVG_DIR, file), 'utf-8')),
    )
    exports.push(`export { default as ${toComponentName(fileName)} } from './icons/${fileName}.js'`)
  }

  writeFileSync(
    path.join(root, 'src', 'index.ts'),
    `${HEADER}\n\nexport { createIcon, type GsIconComponent, type GsIconProps } from './create-icon.js'\n\n${exports.join('\n')}\n`,
  )

  console.log(`Generated ${files.length} icon components`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main()
}
