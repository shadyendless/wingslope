/**
 * Generates Tailwind `@custom-variant` rules from `src/variants/variants.json`.
 *
 * Every selector is wrapped in `:where()` so variants add no specificity. Variants are emitted in
 * file order, which is their priority order (later entries win a conflict).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const VARIANTS_DIR = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'variants',
)

/**
 * A variant is either a selector list, or `{ media, selector }` to also gate it behind a media query.
 * @typedef {string | { media: string, selector: string }} VariantDefinition
 */

/** @param {Record<string, VariantDefinition>} variants */
export function generateVariantsCss(variants) {
  const lines = Object.entries(variants).map(([name, definition]) =>
    typeof definition === 'string'
      ? `@custom-variant ${name} (&:where(${definition}));`
      : `@custom-variant ${name} {\n  @media ${definition.media} {\n    &:where(${definition.selector}) {\n      @slot;\n    }\n  }\n}`,
  )
  return `/* Generated by scripts/generate-variants.mjs. Do not edit by hand. */\n\n${lines.join('\n')}\n`
}

export function main() {
  const variants = JSON.parse(readFileSync(path.join(VARIANTS_DIR, 'variants.json'), 'utf-8'))
  writeFileSync(path.join(VARIANTS_DIR, 'variants.css'), generateVariantsCss(variants), 'utf-8')
  console.log(`Generated variants.css (${Object.keys(variants).length} variants)`)
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main()
}
